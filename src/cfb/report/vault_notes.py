"""Write the number-heavy Obsidian notes from the latest results, so the vault never goes stale.

Plain-language version: after every run, this script copies the newest scores and forecasts
into the vault as readable Markdown tables. Hand-written notes (the "why") link to these
auto notes (the "what"), so the facts always match the latest run.

Writes:
    vault/04 Models/Algorithm Comparison.md
    vault/04 Models/Model Card.md
    vault/06 Predictions/<season> Title Odds.md
    vault/06 Predictions/Upcoming Games.md
    vault/00 Home.md   (only the "## Status now" section is replaced)

Run:  python -m cfb.report.vault_notes
"""

from __future__ import annotations

import json
import re
from datetime import datetime, timezone

import pandas as pd

from cfb.config import CURRENT_SEASON, MODELS_DIR, REPORTS, VAULT
from cfb.eval.backtest import OUT as BT
from cfb.report.build_report import FEATURE_LABELS, NICE

CH = REPORTS / "championship"
SPOTLIGHT = ["Michigan", "Michigan State"]          # teams that get their own section
SUBSETS = {"all_fbs_games": "All games with an FBS team", "fbs_vs_fbs": "FBS vs FBS only",
           "games_with_vegas_line": "Games with a Vegas line", "bowls_and_playoff": "Bowls and playoff",
           "early_season_wk1_4": "Weeks 1-4 (many mismatches vs small schools)"}
AUTO = ("> Auto-generated by `python -m cfb.report.vault_notes` on {ts}. Don't edit by hand: "
        "the next run overwrites it. Change the generator instead.")


def _now() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")


def name(model: str) -> str:
    return NICE.get(model, model).replace(" (winner)", "")


def pct(x: float, d: int = 1) -> str:
    if pd.isna(x):
        return "n/a"
    if x == 0:
        return "0%"
    if 0 < x < 0.5 * 10 ** -(d + 2):                    # too small to show at this precision
        return f"<{10 ** -d:.{d}f}%"
    if 1 - 0.5 * 10 ** -(d + 2) <= x < 1:               # don't round a 99.8% favorite up to "100%"
        return f">{100 - 10 ** -d:.{d}f}%"
    return f"{100 * x:.{d}f}%"


def et_date(ts: str) -> str:
    """UTC kickoff time -> US Eastern calendar date (how fans name game days)."""
    return pd.Timestamp(ts).tz_convert("America/New_York").strftime("%a %b %d, %Y")


def table(df: pd.DataFrame) -> str:
    cols = [str(c) for c in df.columns]
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for row in df.itertuples(index=False):
        lines.append("| " + " | ".join("" if pd.isna(v) else str(v) for v in row) + " |")
    return "\n".join(lines)


def write(rel: str, text: str) -> None:
    path = VAULT / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text.rstrip() + "\n", encoding="utf-8")
    print("wrote", path.relative_to(VAULT.parent))


