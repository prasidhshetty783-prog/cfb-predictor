def algorithm_comparison(card: dict, ts: str) -> None:
    m = pd.read_csv(BT / "metrics_overall.csv")
    sig = pd.read_csv(BT / "significance.csv").set_index("model")
    vegas = pd.read_csv(BT / "vs_vegas.csv")
    winner = card["algorithm"]
    allg = m[m["subset"] == "all_fbs_games"].copy()
    full = allg[allg["model"].isin(sig.index)].sort_values("log_loss")
    rows = []
    for i, r in enumerate(full.itertuples(), 1):
        s = sig.loc[r.model]
        tied = "leader" if s["diff_vs_leader"] == 0 else ("yes" if not s["significantly_worse"] else "no")
        rows.append({
            "#": i, "Algorithm": ("**" + name(r.model) + "**") if r.model == winner else name(r.model),
            "Log loss": f"{r.log_loss:.4f}", "95% CI": f"{s['ci_low']:.3f} to {s['ci_high']:.3f}",
            "Accuracy": pct(r.accuracy), "Recall: home wins": pct(r.recall_home),
            "Recall: away wins": pct(r.recall_away), "Upset recall": pct(r.upset_recall),
            "Calibration error": f"{r.ece:.3f}", "Right when 80%+ sure": pct(r.acc_when_80pct_sure),
            "Tied with leader?": tied})
    partial = allg[~allg["model"].isin(sig.index)]
    part_txt = "".join(
        (f"\n- {name(r.model)} (benchmark only, never a model input): log loss {r.log_loss:.4f}, accuracy "
         f"{pct(r.accuracy)} on the {r.n:,} games that had a line." if r.model == "vegas_spread" else
         f"\n- {name(r.model)}: log loss {r.log_loss:.4f}, accuracy {pct(r.accuracy)} on only {r.n:,} games "
         "(it doesn't cover every game, so it isn't ranked with the others).") for r in partial.itertuples())
    v = vegas.copy()
    v["Algorithm"] = [("**" + name(x) + "**") if x == winner else name(x) for x in v["model"]]
    v = v.assign(**{"Log loss": v["log_loss"].map("{:.4f}".format),
                    "Behind Vegas by": v["gap_to_vegas"].map("{:+.4f}".format),
                    "95% CI of the gap": [f"{a:+.4f} to {b:+.4f}" for a, b in zip(v["gap_ci_low"], v["gap_ci_high"], strict=True)],
                    "Accuracy": v["accuracy"].map(pct)})
    sub = m[m["model"] == winner][["subset", "n", "log_loss", "accuracy", "recall_home", "recall_away"]]
    sub = sub.assign(subset=sub["subset"].map(lambda x: SUBSETS.get(x, x)), n=sub["n"].map("{:,}".format),
                     log_loss=sub["log_loss"].map("{:.4f}".format), accuracy=sub["accuracy"].map(pct),
                     recall_home=sub["recall_home"].map(pct), recall_away=sub["recall_away"].map(pct))
    sub.columns = ["Game type", "Games", "Log loss", "Accuracy", "Recall: home wins", "Recall: away wins"]
    sel = card["selection"]
    w = full[full["model"] == winner].iloc[0]
    text = f"""---
tags: [models, auto]
generated: {ts}
---
# Algorithm Comparison

{AUTO.format(ts=ts)}

**Winner: {name(winner)}.** It picked {pct(w.accuracy)} of {int(w.n):,} test games (2014-2025) correctly,
with log loss {w.log_loss:.4f}. The raw leader was {name(sel['leader'])} ({sel['leader_log_loss']:.4f}),
but it is not significantly better, so the pre-registered rule picks the simpler tied model:
*{sel['rule']}.* See [[Evaluation Protocol]] and [[EXP-001 Algorithm Bake-off]].

## Scoreboard: every FBS game, 2014-2025 (each season predicted using only earlier seasons)
{table(pd.DataFrame(rows))}

"Tied with leader?" uses a bootstrap test by game-week (2,000 resamples) with Holm correction.
Not in the ranking:{part_txt or ' none.'}

## Versus the Vegas closing line (games that had a line)
{table(v[["Algorithm", "Log loss", "Behind Vegas by", "95% CI of the gap", "Accuracy"]])}

Vegas is only a yardstick. It is never a model input.

## Winner by type of game
{table(sub)}

## How to read the columns
- **Log loss**: how surprised the model is by what really happened. Lower is better. Picking 50/50 every game scores 0.693.
- **Accuracy**: share of games where the team we favored won.
- **Recall: home / away wins**: of the games the home (or away) team really won, the share we called.
- **Upset recall**: of the games the Vegas underdog won, the share we picked correctly.
- **Calibration error (ECE)**: when we say 70%, do teams win about 70%? 0 is perfect.
- **Right when 80%+ sure**: accuracy on the games where the model was at least 80% confident.
More terms: [[Glossary]].
"""
    write("04 Models/Algorithm Comparison.md", text)


def model_card_note(card: dict, ts: str) -> None:
    t = card["test_results_2014_2025"]
    coefs = pd.read_csv(BT / "final_model_coefficients.csv")
    coefs = coefs.reindex(coefs["weight"].abs().sort_values(ascending=False).index).head(10)
    coefs = pd.DataFrame({"Clue": [FEATURE_LABELS.get(f, f) for f in coefs["feature"]],
                          "Column": ["`" + f + "`" for f in coefs["feature"]],
                          "Weight": coefs["weight"].map("{:+.2f}".format)})
    subsets = "\n".join(f"- {SUBSETS.get(k, k)}: {v:.4f}" for k, v in card["by_subset_log_loss"].items())
    weak = "\n".join(f"- {x}" for x in card["known_weaknesses"])
    text = f"""---
tags: [models, auto]
generated: {ts}
---
# Model Card: {card['name']}

{AUTO.format(ts=ts)}

**What it is:** {card['plain_description']}
**Algorithm:** `{card['algorithm']}` with {json.dumps(card['params'])}. Typical miss: about
{card['sigma_points']:.1f} points (the spread used to turn a margin into a win chance).
**Trained on:** {card['n_training_games']:,} games, seasons {card['trained_on_seasons'][0]}-{card['trained_on_seasons'][1]}.
**Inputs:** {len(card['features'])} pregame clues, all known before kickoff. See [[Feature Catalog]].
**Saved as:** `models/final_model.joblib` (created {card['created_at'][:10]}).

## How good is it (walk-forward test, 2014-2025, {t['n']:,} games)
| Measure | Value | Meaning |
|---|---|---|
| Accuracy | {pct(t['accuracy'])} | Picks the winner about {round(t['accuracy'] * 4)} times out of 4 |
| Log loss | {t['log_loss']:.4f} | Lower is better; a coin flip is 0.693 |
| Brier skill | {pct(t['brier_skill'])} | Improvement over always guessing the home-win rate |
| AUC | {t['auc']:.3f} | Chance it ranks a real winner above a real loser |
| Recall: home wins / away wins | {pct(t['recall_home'])} / {pct(t['recall_away'])} | Share of real wins it called |
| Balanced accuracy | {pct(t['balanced_accuracy'])} | Average of the two recalls |
| Calibration error (ECE) | {t['ece']:.3f} | When it says 70%, teams win about 70% |
| Calibration slope | {t['calib_slope']:.2f} | 1.00 is perfect; above 1 means slightly too timid |
| When 80%+ sure | right {pct(t['acc_when_80pct_sure'])} | Happens in {pct(t['share_80pct_sure'])} of games |
| Upsets called | {pct(t['upset_recall'])} | Upsets are hard for every model |
| Gap to Vegas | +{card['gap_to_vegas_log_loss']:.4f} log loss | Close, but Vegas is still better |

Log loss by type of game:
{subsets}

## Biggest clues (weights on standardized inputs, predicting the home margin)
{table(coefs)}

## Known weaknesses
{weak}

## Why this algorithm
{card['selection']['rule']}. Tied with the leader: {', '.join(name(x) for x in card['selection']['statistically_tied_with_leader'])}.
Details: [[Algorithm Comparison]], [[Decisions Log]].
"""
    write("04 Models/Model Card.md", text)


def title_odds_note(ts: str) -> tuple[pd.DataFrame, dict] | None:
    path = CH / f"title_odds_{CURRENT_SEASON}.csv"
    if not path.exists():
        return None
    odds = pd.read_csv(path)
    meta = json.loads((CH / f"title_odds_{CURRENT_SEASON}_meta.json").read_text())
    top = odds.head(25)
    show = pd.DataFrame({
        "#": range(1, len(top) + 1), "Team": top["team"], "Conf.": top["conference"],
        "Record": top["record_now"], "Power": top["power_rating"].map("{:+.1f}".format),
        "Exp. wins": top["exp_wins"].map("{:.1f}".format), "Conf. title": top["p_conf_title"].map(pct),
        "Make CFP": top["p_playoff"].map(pct), "Top-4 bye": top["p_top4_bye"].map(pct),
        "Semifinal": top["p_semifinal"].map(pct), "Final": top["p_final"].map(pct),
        "**Title**": top["p_title"].map(pct)})
    spot = odds[odds["team"].isin(SPOTLIGHT)]
    spot_txt = "\n".join(
        f"- **{r.team}** ({r.record_now}): title {pct(r.p_title, 2)}, make CFP {pct(r.p_playoff)}, "
        f"expected wins {r.exp_wins:.1f}, power rating {r.power_rating:+.1f}." for r in spot.itertuples())
    assumptions = "\n".join(f"- {a}" for a in meta.get("assumptions", []))
    n_feat = len(json.loads((MODELS_DIR / "model_card.json").read_text())["features"])
    text = f"""---
tags: [predictions, auto]
generated: {ts}
season: {CURRENT_SEASON}
---
# {CURRENT_SEASON} Title Odds (title game in January {CURRENT_SEASON + 1})

{AUTO.format(ts=ts)}

**Favorite: {odds.iloc[0]['team']} at {pct(odds.iloc[0]['p_title'])}.** No team is above
50%: a 12-team bracket means even the best team must usually win three or four playoff games.
Based on {meta['n_sims']:,} simulated seasons, using games through {et_date(meta['data_through'])}
({meta['games_completed']} played, {meta['games_simulated']} still to simulate).

## Top 25
{table(show)}

"Power" = points better than an average FBS team on a neutral field (the opponent-adjusted
scoring rating). It is only one of the model's {n_feat} clues: the model also weighs recruiting
talent, Elo, returning players and more. So a team with a top Power but modest recruiting gets
less credit than its Power alone suggests. That is a known risk: see [[Model Card]].

## Spotlight
{spot_txt or '- (no spotlight teams found)'}

## How it works
1. Every remaining game is played 10,000 times with the final model. Each simulated season also
   nudges every team's strength up or down (about {meta['rating_uncertainty_tau_points']:.1f} points), because
   we're never sure exactly how good a team is. Single games add noise of about
   {meta['game_noise_sigma_points']:.1f} points.
2. Conference title games are set from the simulated standings.
3. A committee emulator, trained on the real CFP rankings 2014-2025, ranks the teams
   ([[EXP-004 Committee Emulator]]).
4. The 12-team field is built with the 2026 rules and the bracket is played out.

Assumptions:
{assumptions}

How much to trust this: [[EXP-003 Champion Backtest]].
"""
    write(f"06 Predictions/{CURRENT_SEASON} Title Odds.md", text)
    return odds, meta


def upcoming_note(ts: str) -> None:
    path = REPORTS / f"predictions_{CURRENT_SEASON}_upcoming.csv"
    if not path.exists():
        return
    p = pd.read_csv(path)
    if p.empty:
        write("06 Predictions/Upcoming Games.md", f"# Upcoming Games\n\n{AUTO.format(ts=ts)}\n\nNo games left.")
        return
    start = pd.to_datetime(p["start_date"], utc=True).dt.tz_convert("America/New_York")
    p["When (ET)"] = [s.strftime("%a %b %d") + (" (time TBD)" if (s.hour, s.minute) == (0, 0)
                                                else s.strftime(", %I:%M %p")) for s in start]
    p["Game"] = [f"{a} {'vs' if n else 'at'} {h}" for a, h, n in zip(p["away_team"], p["home_team"],
                                                                         p["neutral_site"].fillna(False), strict=True)]
    p["Pick"] = p["favorite"]
    p["Win chance"] = p["favorite_win_prob"].map(lambda x: pct(x, 0))
    p["By (points)"] = p["favorite_by_points"].map("{:.1f}".format)
    cols = ["When (ET)", "Game", "Pick", "Win chance", "By (points)"]
    week = int(p["week"].min())
    nxt = p[p["week"] == week]
    spot_parts = []
    for team in SPOTLIGHT:
        t = p[(p["home_team"] == team) | (p["away_team"] == team)]
        if len(t):
            spot_parts.append(f"### {team}\n" + table(t[["week"] + cols].rename(columns={"week": "Week"})))
    close = p.loc[p["favorite_win_prob"] < 0.55, cols].head(12)
    text = f"""---
tags: [predictions, auto]
generated: {ts}
---
# Upcoming Games ({CURRENT_SEASON})

{AUTO.format(ts=ts)}

{len(p)} games left. Every game is in `reports/predictions_{CURRENT_SEASON}_upcoming.csv`.
"Win chance" is for the picked team. "By" is the predicted winning margin.
Rule of thumb: 60% is a lean, 75% is solid, 90% is a near-lock (but still loses 1 in 10).

## Week {week}
{table(nxt[cols])}

## Spotlight teams (rest of the season)
{chr(10).join(spot_parts) if spot_parts else 'None.'}

## Closest games left (pick under 55%)
{table(close) if len(close) else 'None.'}
"""
    write("06 Predictions/Upcoming Games.md", text)


def home_status(card: dict, odds_meta: tuple[pd.DataFrame, dict] | None, ts: str) -> None:
    home = VAULT / "00 Home.md"
    if not home.exists():
        print("skip status: vault/00 Home.md not found")
        return
    t = card["test_results_2014_2025"]
    lines = [f"- Updated {ts}.",
             f"- Model: {card['name']}. Picks {pct(t['accuracy'])} of 2014-2025 games right; "
             f"log loss {t['log_loss']:.3f}; {card['gap_to_vegas_log_loss']:+.3f} behind Vegas. [[Model Card]]"]
    if odds_meta:
        odds, meta = odds_meta
        top3 = ", ".join(f"{r.team} {pct(r.p_title)}" for r in odds.head(3).itertuples())
        lines.append(f"- {CURRENT_SEASON} title odds (games through {et_date(meta['data_through'])}): {top3}. "
                     f"[[{CURRENT_SEASON} Title Odds]]")
        spot = odds[odds["team"].isin(SPOTLIGHT)]
        if len(spot):
            lines.append("- Spotlight: " + "; ".join(f"{r.team} title {pct(r.p_title, 2)}" for r in spot.itertuples())
                         + ". [[Upcoming Games]]")
    lines.append("- Next steps: [[Roadmap]].")
    block = "## Status now\n" + "\n".join(lines) + "\n"
    text = home.read_text(encoding="utf-8")
    new, n = re.subn(r"## Status now\s*\n.*?(?=\n## |\Z)", block.rstrip("\n") + "\n", text, count=1,
                     flags=re.S)
    if n == 0:
        new = text.rstrip() + "\n\n" + block
    home.write_text(new.rstrip() + "\n", encoding="utf-8")
    print("updated status in vault/00 Home.md")


def main() -> None:
    ts = _now()
    card = json.loads((MODELS_DIR / "model_card.json").read_text())
    algorithm_comparison(card, ts)
    model_card_note(card, ts)
    odds_meta = title_odds_note(ts)
    upcoming_note(ts)
    home_status(card, odds_meta, ts)


if __name__ == "__main__":
    main()
